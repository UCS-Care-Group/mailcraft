#[test]
fn names_get_their_verdicts() {
    for (name, want) in TABLE {
        assert_eq!(verdict(name), *want, "{name:?}");
    }
}

#[test]
fn every_blocked_kind_is_in_the_table() {
    for ext in BLOCKED {
        let name = format!("a.{ext}");
        assert!(TABLE.iter().any(|(n, v)| *n == name && *v == Blocked), "{name} has no row in TABLE");
    }
}
